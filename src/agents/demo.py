"""Phase 11.5 live demo with the local model (Ollama). Writes results/tables/phase11_demo.md.

A  Writer (LLM) + Skeptic (rules) + reviewer (LLM) on the headline topic.
B  Bad start: a scripted first draft that writes its own number; the LLM must repair it from feedback.
C  LLM Mapper vs baseline on a few titles.

Run from the repo root:  python -m src.agents.demo
"""
from __future__ import annotations

import time

from src.agents.llm import available, cfg
from src.agents.mapper import llm_chooser, map_title, map_title_llm
from src.agents.pipeline import llm_reviewer, run
from src.agents.writer import WriterDraft, keys_for, llm_writer
from src.utils.config import REPO_ROOT

TABLE = REPO_ROOT / "results" / "tables" / "phase11_demo.md"
TOPIC = ("The headline estimate for 22-25-year-olds in the most AI-exposed occupations (Q5), its confidence "
         "interval and verdict, and what it is relative to.")
KEYS = ("phase8_main.headline.", "phase8_main.l3_within_age_q5_vs_q1.", "phase8_main.pretrend.")
TITLES = ["data scientist", "software engineer", "junior accountant", "warehouse associate", "UX designer"]


def history(out) -> list[str]:
    lines = ["| Attempt | Template (LLM output) | Rendered claim | Issues |", "|---|---|---|---|"]
    for h in out["history"]:
        esc = lambda s: (s or "—").replace("|", "/")
        issues = "; ".join(f"{i['rule']}: {i['detail']}" + (f' ("{i["quote"]}")' if i["quote"] else "") for i in h["issues"])
        lines.append(f"| {h['attempt']} | {esc(h['template'])} | {esc(h['claim'])} | {esc(issues or 'passed')} |")
    return lines + ["", f"Status: **{out['status']}** after {out['attempts']} draft(s) ({out['attempts'] - 1} revision(s)).", ""]


def main() -> None:
    model = cfg()["model"]
    assert available(model), f"{model} is not available on {cfg()['host']}"
    keys = keys_for(*KEYS)
    writer, reviewer = llm_writer(), llm_reviewer()

    t = time.time()
    a = run(TOPIC, keys, writer, reviewer, cfg()["max_revisions"])
    ta = time.time() - t

    bad = WriterDraft(template="Young workers in AI-exposed jobs lost 19% of employment because of AI.", label="DESCRIPTIVE")
    calls = {"n": 0}

    def bad_then_llm(topic, k, feedback):
        calls["n"] += 1
        return bad if calls["n"] == 1 else writer(topic, k, feedback)

    t = time.time()
    b = run(TOPIC, keys, bad_then_llm, reviewer, cfg()["max_revisions"])
    tb = time.time() - t

    chooser = llm_chooser()
    mapped = [(ti, map_title(ti, 1)[0], map_title_llm(ti, chooser)) for ti in TITLES]

    lines = ["# Phase 11.5 live demo (local LLM). Agent output, not analysis", "",
             f"Generated by `python -m src.agents.demo`. Model `{model}` via Ollama, temperature {cfg()['temperature']}, "
             f"thinking {'on' if cfg().get('think') else 'off'}, max revisions {cfg()['max_revisions']}. "
             "Every number in a rendered claim was filled in by code from results/registry; the model wrote none.", "",
             "Graph: write -> render -> skeptic -> accepted (end) / revise (back to write) / rejected (end).", "",
             f"## A. Headline claim, written by the model ({ta:.0f} s)", "", *history(a),
             f"## B. Bad first draft, repaired by the model ({tb:.0f} s)", "",
             "Draft 1 is scripted (it writes its own number and causal wording); later drafts are the model's.", "",
             *history(b),
             "## C. Mapper: baseline vs LLM (choosing among the baseline's top 25)", "",
             "| Title | Baseline top-1 | LLM choice |", "|---|---|---|"]
    lines += [f"| {ti} | {b0.occ2010} {b0.label} | {l.occ2010} {l.label} |" for ti, b0, l in mapped]
    TABLE.write_text("\n".join(lines + [""]), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
