"""Phase 6, Stage C: the descriptive replication, first age x exposure view. DESCRIPTIVE.

C1  Employment index by quintile, ages 22-25 (the payroll paper's figure).
C2  The same index for every age group, small multiples on one shared axis.
C3  Unadjusted triple-difference ratio:
        R_t = (E[Q5, a] / E[Q1, a]) / (E[Q5, 35-49] / E[Q1, 35-49]),  a = 22-25 and 26-34,
    indexed to bin -1 = 100. No fixed effects, no weights beyond the outcome, no inference:
    not the Section 8 estimate.
C4  Exploratory occupation share (Section 6): share of employed 22-25-year-olds in each quintile.

Same bins, base and sample as Stage B. Run from the repo root:  python -m src.analysis.eda_stage_c
"""
from __future__ import annotations

import matplotlib.pyplot as plt
import pandas as pd

from src.analysis.eda_stage_b import (BASE_BIN, FIGDIR, INK, INK2, NOTE, REPO_ROOT, SERIES, SURFACE, bin_start,
                                      binned, draw, figure, table)
from src.utils.config import load_settings

TABLE = REPO_ROOT / "results" / "tables" / "phase6_stage_c.md"
AGES = ["22-25", "26-34", "35-49", "50-64"]


def grid(idxs: dict[str, pd.DataFrame], name: str) -> None:
    lo = min(i.min().min() for i in idxs.values()) - 2
    hi = max(i.max().max() for i in idxs.values()) + 2
    fig, axes = plt.subplots(2, 2, figsize=(11, 7), sharey=True, facecolor=SURFACE)
    for ax, (age, idx) in zip(axes.flat, idxs.items()):
        draw(ax, idx, ylim=(lo, hi))
        ax.set_title(f"Ages {age}", loc="left", color=INK, fontsize=10)
    fig.suptitle("DESCRIPTIVE. C2: employment index by exposure quintile, each age group (Sep-Nov 2022 = 100)",
                 x=0.01, ha="left", color=INK, fontsize=11)
    fig.text(0.01, 0.005, NOTE, color=INK2, fontsize=8)
    fig.tight_layout(rect=(0, 0.02, 1, 0.97))
    fig.savefig(FIGDIR / name, dpi=150)


def main() -> None:
    p = pd.read_parquet(load_settings()["paths"]["processed"] / "panel_occ_age_month.parquet",
                        columns=["age_group", "quintile", "ym", "emp_w", "main_sample"])
    p = p[p.main_sample]
    p["quintile"] = "Q" + p.quintile.astype(str)

    levels, idxs = {}, {}
    for age in AGES:
        levels[age], idxs[age] = binned(p[p.age_group == age], "quintile")
    figure(idxs["22-25"], "DESCRIPTIVE. C1: employment by exposure quintile, ages 22-25", "c1_young_by_quintile.png")
    grid(idxs, "c2_all_ages_by_quintile.png")

    ratio = lambda age: (levels[age]["Q5"] / levels[age]["Q1"]) / (levels["35-49"]["Q5"] / levels["35-49"]["Q1"])
    r = pd.DataFrame({a: ratio(a) for a in ("22-25", "26-34")})
    r = 100 * r / r.loc[BASE_BIN]
    figure(r, "DESCRIPTIVE. C3: unadjusted ratio (Q5/Q1 at age a) / (Q5/Q1 at 35-49)", "c3_unadjusted_ratio.png",
           ylabel="Ratio index, Sep-Nov 2022 = 100", colors=SERIES[:2])

    y = levels["22-25"]
    share = 100 * y.div(y.sum(axis=1), axis=0)
    figure(share, "DESCRIPTIVE. C4: share of employed 22-25-year-olds in each quintile (%)", "c4_young_share.png",
           ylabel="Percent of employed 22-25", ref=None)

    lines = ["# Phase 6, Stage C: first age x exposure view. DESCRIPTIVE", "",
             "Generated by `python -m src.analysis.eda_stage_c`. Index of average monthly weighted employment per",
             "Section 9 quarterly bin, bin -1 (Sep-Nov 2022) = 100; main-sample months. No model, no fixed effects,",
             "no inference, no causal claim. C3 is not the Section 8 estimate.", ""]
    for age in AGES:
        fig = "c1_young_by_quintile.png" if age == "22-25" else "c2_all_ages_by_quintile.png"
        lines += table(levels[age], idxs[age], f"## {'C1' if age == '22-25' else 'C2'}. Ages {age}, by quintile", fig)
    lines += ["## C3. Unadjusted ratio, (Q5/Q1 at age a) / (Q5/Q1 at 35-49), Sep-Nov 2022 = 100", "",
              "Figure: `results/figures/c3_unadjusted_ratio.png`. Below 100 = Q5 fell relative to Q1 for the young",
              "group by more than for ages 35-49, since Sep-Nov 2022. Raw ratio of weighted counts.", "",
              "| Bin start | 22-25 | 26-34 |", "|---|---|---|"]
    lines += [f"| {bin_start(b):%Y-%m} | {v['22-25']:.1f} | {v['26-34']:.1f} |" for b, v in r.iterrows()]
    lines += ["", "## C4. Share of employed 22-25-year-olds in each quintile (%)", "",
              "Figure: `results/figures/c4_young_share.png`. Exploratory outcome (Section 6).", "",
              "| Bin start | " + " | ".join(share.columns) + " |", "|---" * (len(share.columns) + 1) + "|"]
    lines += [f"| {bin_start(b):%Y-%m} | " + " | ".join(f"{x:.1f}" for x in v) + " |" for b, v in share.iterrows()]
    TABLE.write_text("\n".join(lines + [""]), encoding="utf-8")
    print(f"Wrote {TABLE.relative_to(REPO_ROOT)} and four figures")


if __name__ == "__main__":
    main()
