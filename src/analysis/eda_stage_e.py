"""Phase 6, Stage E: descriptive comparison with the payroll paper (Section 18). DESCRIPTIVE.

The payroll paper reports employment of 22-25-year-olds in AI-exposed occupations 13-19% below
less-exposed peers (main sample: full-time workers). Raw CPS analogues, as % changes:
  - young gap:   log(Q5 / Q1) at ages 22-25
  - triple ratio: young gap minus log(Q5 / Q1) at ages 35-49   (Stage C, C3)
each measured as (window average) minus (baseline), for all employed and for full-time workers.
No fixed effects, no inference, no verdict: not the Section 8 estimate, not comparable in
construction (household survey vs payroll records).

Run from the repo root:  python -m src.analysis.eda_stage_e
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from src.analysis.eda_stage_b import BASE_BIN, REPO_ROOT, add_bin, bin_start
from src.utils.config import load_settings

TABLE = REPO_ROOT / "results" / "tables" / "phase6_stage_e.md"
LATEST = 4   # most recent bins, about the last year


def gaps(p: pd.DataFrame, col: str) -> pd.DataFrame:
    s = add_bin(p).groupby(["bin", "age_group", "quintile"])[col].sum().unstack(["age_group", "quintile"])
    young = np.log(s[("22-25", 5)] / s[("22-25", 1)])
    return pd.DataFrame({"young gap": young, "triple ratio": young - np.log(s[("35-49", 5)] / s[("35-49", 1)])})


def main() -> None:
    p = pd.read_parquet(load_settings()["paths"]["processed"] / "panel_occ_age_month.parquet",
                        columns=["age_group", "quintile", "ym", "emp_w", "emp_w_fulltime", "main_sample"])
    p = p[p.main_sample]
    rows = []
    for col, sample in (("emp_w", "All employed"), ("emp_w_fulltime", "Full-time (35+ usual hours)")):
        g = gaps(p, col)
        pre, post = g[g.index < 0], g[g.index >= 0]
        for measure in g.columns:
            for base_name, base in (("Sep-Nov 2022 bin", g.loc[BASE_BIN, measure]), ("pre-period average", pre[measure].mean())):
                for win_name, win in (("all post bins", post[measure].mean()), (f"latest {LATEST} bins", post[measure].tail(LATEST).mean())):
                    rows.append((sample, measure, base_name, win_name, 100 * (np.exp(win - base) - 1)))
        sd = 100 * pre["young gap"].std()
    last = post.index[-LATEST:]
    lines = ["# Phase 6, Stage E: comparison with the payroll paper. DESCRIPTIVE", "",
             "Generated by `python -m src.analysis.eda_stage_e`. Raw ratios of weighted employment per Section 9 bin;",
             "main-sample months. Change = exp(window average of the log ratio minus baseline) - 1. No fixed effects, no",
             "inference, no verdict. Not the Section 8 estimate, and not built like the payroll paper's figure",
             "(household survey not payroll records; exposure quintiles not built the same way; no trend adjustment).", "",
             f"Latest {LATEST} bins: {bin_start(last[0]):%Y-%m} to {bin_start(last[-1]) + pd.DateOffset(months=2):%Y-%m} "
             "(includes the Oct 2025 gap and the late-collected Nov 2025).", "",
             "Payroll paper (Section 18): 22-25-year-olds in AI-exposed occupations about 13-19% below less-exposed",
             "peers (13% Aug 2025 version; 16% with firm-level controls, Nov 2025; 19% Aug 2026 version; main sample",
             "full-time workers).", "",
             "| Sample | Measure | Baseline | Window | Change (%) |", "|---|---|---|---|---|"]
    lines += [f"| {a} | {b} | {c} | {d} | {e:+.1f} |" for a, b, c, d, e in rows]
    lines += ["", f"Noise guide: the young gap's standard deviation across pre-period bins (full-time sample) is about "
              f"{sd:.1f} log points.", ""]
    TABLE.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
