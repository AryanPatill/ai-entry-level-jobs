"""Phase 7, Step 7.6a and T4(b): inputs for the Section 12 threat tests.

growth  Threat 2 control: occupation employment growth over `threat2_growth_window`
        (2015-01 to 2020-02, Aryan 2026-11-03), all ages pooled:
            log(mean monthly emp, last 12 months of the window) - log(mean monthly emp, first 12 months)
        A pre-period outcome; it enters Phase 9 only as growth x age x post.
soc15   Threat 4(b): computer and mathematical occupations = 2010 Census codes whose SOC 2018
        targets are all in SOC major group 15 (default proposed 2026-11-03; Aryan to confirm).

Run from the repo root:  python -m src.analysis.threat_inputs
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from src.crosswalks.occupation_exposure import MAP_FILE
from src.data.build_panel import ym
from src.utils.config import REPO_ROOT, load_settings

OUT = "threat_inputs.parquet"
TABLE = REPO_ROOT / "results" / "tables" / "phase7_threat_inputs.md"


def growth(panel: pd.DataFrame, window: list[str]) -> pd.Series:
    start, end = ym(window[0]), ym(window[1])
    months = sorted(m for m in panel.ym.unique() if start <= m <= end)
    first, last = months[:12], months[-12:]
    occ = panel.groupby(["occ2010", "ym"]).emp_w.sum().unstack()
    with np.errstate(divide="ignore"):
        return np.log(occ[last].mean(axis=1)) - np.log(occ[first].mean(axis=1))


def soc15(occ_map: pd.DataFrame) -> pd.Series:
    socs = occ_map.set_index(occ_map.census2010.astype(int)).soc2018.fillna("").str.split()
    return socs.map(lambda s: bool(s) and all(c.startswith("15-") for c in s))


def main() -> None:
    s = load_settings()
    panel = pd.read_parquet(s["paths"]["processed"] / "panel_occ_age_month.parquet", columns=["occ2010", "ym", "emp_w"])
    g = growth(panel, s["design"]["threat2_growth_window"])
    flag = soc15(pd.read_csv(MAP_FILE, dtype=str)).reindex(g.index).fillna(False)
    out = pd.DataFrame({"occ2010": g.index, "growth": g.replace([np.inf, -np.inf], np.nan).values, "soc15": flag.values})
    out.to_parquet(s["paths"]["interim"] / OUT, index=False)

    bad = out.growth.isna().sum()
    lines = ["# Phase 7: inputs for the threat tests (7.6a, T4b)", "",
             "Generated by `python -m src.analysis.threat_inputs`. Values stored in data/interim (not committed).", "",
             f"## Threat 2 growth control, window {s['design']['threat2_growth_window'][0]} to {s['design']['threat2_growth_window'][1]}", "",
             f"- Occupations: {len(out)}; growth undefined (zero employment in the first or last 12 months): {bad}.",
             f"- Distribution of log growth (all ages pooled, pre-period only): 10th pct {out.growth.quantile(.1):+.3f}, "
             f"median {out.growth.median():+.3f}, 90th pct {out.growth.quantile(.9):+.3f}.", "",
             "## Threat 4(b): computer and mathematical occupations (all SOC targets in group 15)", "",
             f"{int(out.soc15.sum())} occupations: " + ", ".join(f"{c:04d}" for c in out.occ2010[out.soc15]), ""]
    TABLE.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    assert soc15(pd.DataFrame({"census2010": ["1", "2", "3"], "soc2018": ["15-1252", "15-1252 11-3021", None]})).tolist() == [True, False, False]
    main()
