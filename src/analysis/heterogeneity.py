"""Phase 10: subgroups (Section 14) and exploratory heterogeneity (Section 15).

Subgroups (Holm-corrected family, Section 10): bachelor's or higher (filter applied to all age groups),
men, women. Same Section 8 model on the subgroup's weighted counts; same Section 11 verdict rule.
Exploratory (Section 15, uncorrected, labelled): headline by broad sector, from the occupation x sector panel.

Run from the repo root:  python -m src.analysis.heterogeneity
"""
from __future__ import annotations

import pandas as pd

from src.analysis.estimate_main import est, pct, record, verdict
from src.analysis.robustness import fit
from src.crosswalks.industry_sectors import SECTOR_NAMES
from src.utils.config import REPO_ROOT, load_settings

TABLE = REPO_ROOT / "results" / "tables" / "phase10_heterogeneity.md"
SUBGROUPS = {"Bachelor's or higher": "emp_w_ba", "Men": "emp_w_men", "Women": "emp_w_women"}


def holm(p: dict[str, float]) -> dict[str, float]:
    order = sorted(p, key=p.get)
    out, run = {}, 0.0
    for i, k in enumerate(order):
        run = max(run, min(1.0, (len(order) - i) * p[k]))
        out[k] = run
    return out


def main() -> None:
    s = load_settings()
    proc = s["paths"]["processed"]
    full = pd.read_parquet(proc / "panel_occ_age_month.parquet")
    p = full[full.main_sample & full.age_group.isin(["22-25", "26-34", "35-49"])]
    sub = {k: fit(p, y=v) for k, v in SUBGROUPS.items()}
    adj = holm({k: r.p for k, r in sub.items()})

    sp = pd.read_parquet(proc / "panel_occ_sector_age_month.parquet")
    sp = sp[sp.main_sample & sp.age_group.isin(["22-25", "26-34", "35-49"])]
    sec = {}
    for k in sorted(sp.sector.unique()):
        try:
            sec[k] = fit(sp[sp.sector == k], fe="occ2010^age_group + occ2010^ym + age_group^ym")
        except Exception as e:   # a sector may lack Q1 or Q5 occupations
            sec[k] = e

    lines = ["# Phase 10: subgroups and exploratory heterogeneity", "",
             "Generated by `python -m src.analysis.heterogeneity`. Headline term Q5 x 22-25 x post, relative to Q1 and",
             "ages 35-49, Section 8 model on each subgroup's weighted counts; CRV1 by occupation.", "",
             "## Subgroups (Section 14; Holm within family)", "",
             "| Subgroup | % change (95% CI) | p | Holm p | Section 11 verdict |", "|---|---|---|---|---|"]
    for k, r in sub.items():
        lines.append(f"| {k} | {pct(r.b)} ({pct(r.lo)} to {pct(r.hi)}) | {r.p:.3f} | {adj[k]:.3f} | "
                     f"{verdict(r.b, r.lo, r.hi, k).split(':')[0]} |")
    lines += ["", "## By broad sector (Section 15; exploratory, uncorrected)", "",
              "| Sector | % change (95% CI) | p |", "|---|---|---|"]
    for k, r in sec.items():
        name = SECTOR_NAMES.get(k, str(k))
        lines.append(f"| {k}. {name} | " + (f"{pct(r.b)} ({pct(r.lo)} to {pct(r.hi)}) | {r.p:.3f} |"
                                              if isinstance(r, pd.Series) else f"not estimable ({type(r).__name__}) | |"))
    lines += ["", "Automation vs augmentation (Section 15): not run. The Eloundou file has no automation/augmentation",
              "split; Section 15 says this is logged as a deviation when the data do not support it.", ""]
    TABLE.write_text("\n".join(lines), encoding="utf-8")
    record("phase10_heterogeneity", {
        "subgroups": {k: {**est(r), "holm_p": round(adj[k], 4), "verdict": verdict(r.b, r.lo, r.hi, k).split(":")[0]} for k, r in sub.items()},
        "sectors_exploratory": {SECTOR_NAMES.get(k, str(k)): est(r) for k, r in sec.items() if isinstance(r, pd.Series)}})
    print("\n".join(lines))


if __name__ == "__main__":
    assert holm({"a": 0.01, "b": 0.04, "c": 0.03}) == {"a": 0.03, "c": 0.06, "b": 0.06}
    main()
