"""Phase 9: randomization inference for the headline (Section 10).

Shuffle exposure across occupations N times (seed fixed), refit the Section 8 model, and compare the
headline coefficient with the shuffled distribution. Shuffling scores under the frozen cutoffs is the
same as shuffling quintile labels across occupations, which is what this does. p = share of shuffles
with |beta| >= |observed beta| (two-sided), counting the observed draw.

Run from the repo root:  python -m src.analysis.randomization_inference
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import pyfixest as pf

from src.analysis.estimate_main import AGES, FE, main_terms
from src.utils.config import REPO_ROOT, load_settings

N, SEED = 1000, 20261104
TABLE = REPO_ROOT / "results" / "tables" / "phase9_randomization_inference.md"


def headline(p: pd.DataFrame) -> float:
    terms = main_terms(p, p.post)
    return float(pf.fepois(f"emp_w ~ {' + '.join(terms)} | {FE}", data=p, vcov="iid").coef()["q5_a22"])


def main() -> None:
    p = pd.read_parquet(load_settings()["paths"]["processed"] / "panel_occ_age_month.parquet",
                        columns=["occ2010", "age_group", "ym", "quintile", "emp_w", "main_sample", "post"])
    p = p[p.main_sample & p.age_group.isin(AGES)].copy()
    observed = headline(p.copy())
    q = p.drop_duplicates("occ2010").set_index("occ2010").quintile
    rng = np.random.default_rng(SEED)
    draws = []
    for i in range(N):
        perm = pd.Series(rng.permutation(q.values), index=q.index)
        draws.append(headline(p.assign(quintile=p.occ2010.map(perm))))
        if (i + 1) % 100 == 0:
            print(f"{i + 1} shuffles done", flush=True)
    draws = np.array(draws)
    p_ri = (1 + (np.abs(draws) >= abs(observed)).sum()) / (N + 1)
    lines = ["# Phase 9: randomization inference for the headline (Section 10)", "",
             "Generated by `python -m src.analysis.randomization_inference`. Quintile labels shuffled across "
             f"occupations {N} times (seed {SEED}); Section 8 model refitted each time.", "",
             f"- Observed headline coefficient: {observed:+.4f}.",
             f"- Shuffled coefficients: mean {draws.mean():+.4f}, sd {draws.std():.4f}, 2.5th-97.5th pct "
             f"{np.quantile(draws, 0.025):+.4f} to {np.quantile(draws, 0.975):+.4f}.",
             f"- Two-sided randomization p = {p_ri:.3f} ({int((np.abs(draws) >= abs(observed)).sum())} of {N} "
             "shuffles at least as extreme).", ""]
    TABLE.write_text("\n".join(lines), encoding="utf-8")
    pd.Series(draws).to_frame("beta").to_parquet(load_settings()["paths"]["interim"] / "ri_draws.parquet", index=False)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
